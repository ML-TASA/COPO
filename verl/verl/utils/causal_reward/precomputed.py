"""Offline (precomputed) causal-reward loading for COPO."""

from __future__ import annotations

import logging
from collections import defaultdict
from typing import Any, Sequence

import torch

from verl.utils.causal_reward.integration import build_causal_reward_tensor

logger = logging.getLogger(__name__)


def _load_store(path: str) -> dict[str, Any]:
    if not path:
        raise ValueError("offline COPO (reward_source=precomputed) requires copo.precomputed_reward_path")
    try:
        data = torch.load(path, map_location="cpu", weights_only=True)
    except (OSError, RuntimeError) as exc:
        raise ValueError(f"failed to load precomputed COPO causal reward from {path!r}: {exc}") from exc
    if not isinstance(data, dict) or not any(k in data for k in ("causal_reward", "sufficiency", "necessity")):
        raise ValueError(
            "precomputed COPO reward store must be a dict with at least one of "
            "causal_reward / sufficiency / necessity keys"
        )
    return data


def _base_sample_id(value: object) -> str:
    value = str(value)
    base, separator, rollout = value.rpartition("::")
    return base if separator and rollout.isdigit() else value


def _reward_rows_equal(store, rows) -> bool:
    first = rows[0]
    for key in ("causal_reward", "sufficiency", "necessity"):
        tensor = store.get(key)
        if tensor is None:
            continue
        values = torch.as_tensor(tensor)
        if any(not torch.equal(values[first], values[row]) for row in rows[1:]):
            return False
    return True


def match_precomputed_trajectory_rows(store, responses, response_mask, sample_ids: Sequence[object]) -> list[int]:
    required = ("sample_ids", "response_token_ids", "response_lengths")
    missing = [key for key in required if key not in store]
    if missing:
        raise ValueError(
            "precomputed COPO store has no verifiable trajectory identity "
            f"({', '.join(missing)} missing); regenerate it with the current reward generator"
        )
    if responses is None or sample_ids is None:
        raise ValueError(
            "precomputed COPO loading requires current responses and sample_ids to verify trajectory identity"
        )
    if responses.shape != response_mask.shape:
        raise ValueError("responses and response_mask must have identical shapes")
    if len(sample_ids) != responses.shape[0]:
        raise ValueError("sample_ids length must equal the response batch size")

    stored_ids = list(store["sample_ids"])
    stored_tokens = torch.as_tensor(store["response_token_ids"], dtype=torch.long)
    stored_lengths = torch.as_tensor(store["response_lengths"], dtype=torch.long)
    if stored_tokens.dim() != 2 or stored_lengths.shape != (stored_tokens.shape[0],):
        raise ValueError("invalid response_token_ids / response_lengths trajectory metadata")
    if len(stored_ids) != stored_tokens.shape[0]:
        raise ValueError("sample_ids and response token metadata have different row counts")

    candidates = defaultdict(list)
    for row, (sample_id, length) in enumerate(zip(stored_ids, stored_lengths.tolist())):
        if length < 0 or length > stored_tokens.shape[1]:
            raise ValueError(f"invalid stored response length {length} at row {row}")
        token_key = tuple(stored_tokens[row, :length].tolist())
        candidates[(_base_sample_id(sample_id), token_key)].append(row)

    matched = []
    for row in range(responses.shape[0]):
        valid = response_mask[row].bool()
        token_key = tuple(responses[row][valid].detach().cpu().long().tolist())
        key = (str(sample_ids[row]), token_key)
        rows = candidates.get(key, [])
        if not rows:
            raise ValueError(
                f"precomputed COPO trajectory mismatch for sample_id={sample_ids[row]!r}, batch row {row}; "
                "the reward store does not label the response generated by this training rollout"
            )
        if len(rows) > 1 and not _reward_rows_equal(store, rows):
            raise ValueError(
                f"ambiguous precomputed COPO trajectories for sample_id={sample_ids[row]!r}: "
                "identical response tokens have different causal rewards"
            )
        matched.append(rows.pop(0))
    return matched


def _validate_and_align(tensor, response_mask, name, row_indices):
    """Shape/device/dtype validation + alignment to ``response_mask``."""
    tensor = torch.as_tensor(tensor, dtype=torch.float32)
    if tensor.dim() != 2:
        raise ValueError(f"{name} must be a 2D (batch, response_length) tensor, got {tuple(tensor.shape)}")
    batch_size, response_length = response_mask.shape
    if row_indices and tensor.shape[0] <= max(row_indices):
        raise ValueError(f"{name} has too few rows for matched trajectories")
    if tensor.shape[1] < response_length:
        raise ValueError(
            f"{name} response length {tensor.shape[1]} < response length {response_length} "
            f"(precompute with >= max_response_length)"
        )
    # Allow a store precomputed to max_response_length to be truncated to the
    # actual padded response length of this batch.
    tensor = tensor[row_indices, :response_length].to(response_mask.device)
    return tensor


def _validate_reasoning_mask(tensor, response_mask, row_indices):
    mask = _validate_and_align(tensor, response_mask, "reasoning_mask", row_indices)
    if not torch.all((mask == 0) | (mask == 1)):
        raise ValueError("reasoning_mask must be binary")
    if torch.any(mask.bool() & ~response_mask.bool()):
        raise ValueError("reasoning_mask selects response padding")
    return mask


def load_offline_causal_reward(response_mask, config, responses=None, sample_ids=None) -> torch.Tensor:
    """Load a ``.pt`` store and return a ``(B, T)`` causal reward aligned to ``response_mask``.

    The store may carry ``causal_reward`` (used verbatim) or ``sufficiency`` /
    ``necessity`` (combined via ``build_causal_reward_tensor``). Rows are selected
    by stable sample ID and exact response token sequence before shape, dtype and
    device alignment.
    """
    store = _load_store(getattr(config, "precomputed_reward_path", None))
    row_indices = match_precomputed_trajectory_rows(store, responses, response_mask, sample_ids)
    sufficiency = necessity = causal_reward = reasoning_mask = None
    if "causal_reward" in store:
        causal_reward = _validate_and_align(
            store["causal_reward"], response_mask, "causal_reward", row_indices
        )
    if "sufficiency" in store:
        sufficiency = _validate_and_align(
            store["sufficiency"], response_mask, "sufficiency", row_indices
        )
    if "necessity" in store:
        necessity = _validate_and_align(
            store["necessity"], response_mask, "necessity", row_indices
        )
    if "reasoning_mask" in store:
        reasoning_mask = _validate_reasoning_mask(store["reasoning_mask"], response_mask, row_indices)
    if causal_reward is None and sufficiency is None and necessity is None:
        raise ValueError("precomputed COPO reward store contains no usable reward tensors")
    return build_causal_reward_tensor(
        response_mask,
        config,
        causal_reward=causal_reward,
        sufficiency_reward=sufficiency,
        necessity_reward=necessity,
        reasoning_mask=reasoning_mask,
    )


def inject_precomputed_reward(data, config) -> dict:
    """Materialize the offline ``.pt`` causal reward into ``data.batch``.

    Writes ``data.batch["copo_causal_rewards"]`` (shape matching
    ``response_mask``) and returns a small metadata dict for logging/metrics.
    """
    response_mask = data.batch["response_mask"]
    sample_ids = data.non_tensor_batch.get("sample_id")
    causal_reward = load_offline_causal_reward(
        response_mask,
        config,
        responses=data.batch.get("responses"),
        sample_ids=sample_ids,
    )
    data.batch["copo_causal_rewards"] = causal_reward
    info = {
        "copo_causal_rewards_loaded": True,
        "copo_causal_reward_shape": tuple(causal_reward.shape),
        "copo_causal_reward_dtype": str(causal_reward.dtype),
        "copo_causal_reward_device": str(causal_reward.device),
        "copo_precomputed_reward_path": getattr(config, "precomputed_reward_path", None),
    }
    logger.warning(
        "offline COPO: reward_source=precomputed loaded causal_reward_shape=%s device=%s dtype=%s",
        tuple(causal_reward.shape),
        causal_reward.device,
        causal_reward.dtype,
    )
    return info
